"""Future expansion placeholders for OpenAstrocytes.

This module contains placeholder implementations for future direct typed dataset exports.
Currently, typed datasets are generated by applying lens transformations to generic Frame
datasets. Future versions may support directly-typed exports that don't require conversion.
"""

##
# Imports

from ._common import (
    ST,
    DatasetInfo,
)
from ._bath_application import BathApplicationFrame
from ._uncaging import UncagingFrame

from dataclasses import dataclass
from typing import (
    Any,
    Type,
)


##
# Dataset indexes

@dataclass
class TypedDatasetIndex:
    """Dataset index for future directly-typed exports.

    This class will provide access to datasets that are pre-typed (BathApplicationFrame,
    UncagingFrame, etc.) without requiring lens conversion from generic Frames.
    Currently unused, as all typed datasets are generated via lens transformations.
    """
    ##
    def __init__( self,
                config: dict[str, Any],
                hive_root: str = '',
            ):
        """Initialize the typed dataset index.

        Args:
            config: Configuration dictionary mapping experiment types to dataset paths
            hive_root: Base URL for the data repository
        """

        # Shortcut
        def _typed_info( name: str, sample_type: Type[ST] )-> DatasetInfo[ST] | None:
            return DatasetInfo._parse(
                config.get( name ), 'typed/' + name,
                sample_type = sample_type,
                hive_root = hive_root,
            )
        
        self.bath_application = _typed_info( 'bath_application', BathApplicationFrame )
        self.uncaging = _typed_info( 'uncaging', UncagingFrame )


